"""Dynamic corridor — center + yellow boundaries fitted from ``lane_area``.

Single-frame, stateless. Per-row centroids of the lane mask in the lower
driving region are fitted to a quadratic; left/right yellow boundaries are
generated by offsetting the center along its analytic normal at each sample
``y``. Output reuses the legacy ``fixed_*`` dict keys so the existing renderer
and ``path_relevance`` helpers are drop-in compatible. Stateful EMA + LANE_OK
/ LANE_WEAK / LANE_LOST gating lives in ``features.dynamic_corridor_tracker``.
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np

DEFAULT_TOP_FRAC = 0.55
DEFAULT_BOTTOM_FRAC = 1.0
DEFAULT_HALF_WIDTH_NEAR_FRAC = 0.22
DEFAULT_HALF_WIDTH_FAR_FRAC = 0.06
DEFAULT_NUM_POINTS = 24
DEFAULT_MIN_ROW_PIXELS = 6
DEFAULT_MIN_ROWS_FOR_FIT = 6
DEFAULT_RESIDUAL_TRIM_FRAC = 0.15

__all__ = [
    "compute_dynamic_corridor", "build_corridor_dict", "FitResult",
    "DEFAULT_TOP_FRAC", "DEFAULT_BOTTOM_FRAC",
    "DEFAULT_HALF_WIDTH_NEAR_FRAC", "DEFAULT_HALF_WIDTH_FAR_FRAC",
    "DEFAULT_NUM_POINTS",
]


@dataclass(slots=True)
class FitResult:
    """Quadratic ``x = a*y^2 + b*y + c`` fit + diagnostics."""
    coeffs: tuple[float, float, float]
    n_points: int
    confidence: float
    rms_residual_px: float


def _row_centroids(
    mask: np.ndarray, top_cut: int, min_row_pixels: int,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    region = mask[top_cut:]
    h, w = region.shape
    bin_mask = (region > 0).astype(np.float32)
    counts = bin_mask.sum(axis=1)
    valid = counts >= float(min_row_pixels)
    if not np.any(valid):
        return (np.empty(0, np.int32), np.empty(0, np.float32), np.empty(0, np.float32))
    cols = np.arange(w, dtype=np.float32)
    sums = bin_mask @ cols
    cx = np.zeros_like(counts)
    cx[valid] = sums[valid] / counts[valid]
    rows = (np.where(valid)[0] + top_cut).astype(np.int32)
    return rows, cx[valid].astype(np.float32), counts[valid].astype(np.float32)


def _fit_quadratic(
    rows: np.ndarray, cx: np.ndarray, counts: np.ndarray,
    *, residual_trim_frac: float, frame_h: int, frame_w: int,
) -> FitResult | None:
    """Robust weighted quadratic fit with one residual-trim pass."""
    if rows.size < DEFAULT_MIN_ROWS_FOR_FIT:
        return None
    y = rows.astype(np.float64)
    x = cx.astype(np.float64)
    w = np.sqrt(np.clip(counts.astype(np.float64), 1.0, None))
    try:
        coeffs = np.polyfit(y, x, 2, w=w)
    except (np.linalg.LinAlgError, ValueError):
        return None
    residuals = np.abs(np.polyval(coeffs, y) - x)
    rows_used = rows.size
    if residuals.size > DEFAULT_MIN_ROWS_FOR_FIT and residual_trim_frac > 0.0:
        trim = max(1, int(round(residuals.size * residual_trim_frac)))
        keep = np.argsort(residuals)[:-trim]
        if keep.size >= DEFAULT_MIN_ROWS_FOR_FIT:
            try:
                coeffs = np.polyfit(y[keep], x[keep], 2, w=w[keep])
                residuals = np.abs(np.polyval(coeffs, y[keep]) - x[keep])
                rows_used = keep.size
            except (np.linalg.LinAlgError, ValueError):
                pass
    rms = float(np.sqrt(np.mean(residuals ** 2))) if residuals.size else 0.0
    sample_span = max(1, frame_h - int(rows.min()))
    coverage = float(rows_used) / float(sample_span)
    density = float(np.mean(counts)) / max(1.0, float(frame_w))
    fit_quality = float(np.exp(-rms / max(1.0, 0.04 * frame_w)))
    confidence = float(np.clip(0.45 * coverage + 0.35 * density + 0.20 * fit_quality, 0.0, 1.0))
    return FitResult(
        coeffs=(float(coeffs[0]), float(coeffs[1]), float(coeffs[2])),
        n_points=rows_used, confidence=confidence, rms_residual_px=rms,
    )


def build_corridor_dict(
    coeffs: tuple[float, float, float],
    *,
    frame_h: int, frame_w: int,
    top_frac: float, bottom_frac: float,
    half_width_near_px: float, half_width_far_px: float,
    num_points: int,
) -> dict:
    """Sample center, build normal-offset boundaries, package as guidance dict.

    Image coords are y-down. For ``x = f(y)``, the unit normal is
    ``N = (-1, f'(y)) / sqrt(1 + f'(y)^2)``. ``left = P + d*N``,
    ``right = P - d*N`` (left lies on the +screen-left side when the curve
    heads down-right). Half-width tapers near→far so the rendered overlay
    matches the perspective footprint of the camera-anchored fallback.
    """
    a, b, c = coeffs
    y_top = max(0.0, float(frame_h) * top_frac)
    y_bot = min(float(frame_h - 1), float(frame_h) * bottom_frac - 1.0)
    if y_bot <= y_top:
        y_bot = float(frame_h - 1)
        y_top = max(0.0, y_bot - 1.0)
    ys = np.linspace(y_top, y_bot, num=num_points, dtype=np.float32)
    xs = (a * ys * ys + b * ys + c).astype(np.float32)
    dx_dy = (2.0 * a * ys + b).astype(np.float32)
    norm = np.sqrt(1.0 + dx_dy * dx_dy).astype(np.float32)
    n_x = (-1.0 / norm).astype(np.float32)
    n_y = (dx_dy / norm).astype(np.float32)
    t = (ys - y_top) / max(y_bot - y_top, 1.0)
    half = (half_width_far_px + (half_width_near_px - half_width_far_px) * t).astype(np.float32)
    # Boundaries are NOT pre-clipped: the normal-offset invariant
    # (||left - center|| == ||right - center|| == half) must hold for math
    # consumers (in-path polygon test, geometry tests). cv2.polylines and
    # cv2.fillPoly clip at the frame edge at draw time.
    left_x = (xs + half * n_x).astype(np.float32)
    left_y = (ys + half * n_y).astype(np.float32)
    right_x = (xs - half * n_x).astype(np.float32)
    right_y = (ys - half * n_y).astype(np.float32)
    cxs = np.clip(xs, 0.0, float(frame_w - 1))
    centerline = np.stack([cxs, ys], axis=1).astype(np.float32)
    left = np.stack([left_x, left_y], axis=1).astype(np.float32)
    right = np.stack([right_x, right_y], axis=1).astype(np.float32)
    polygon = np.vstack([left, right[::-1]]).astype(np.float32)
    return {
        "fixed_centerline_pts_img": centerline,
        "fixed_corridor_left_pts_img": left,
        "fixed_corridor_right_pts_img": right,
        "fixed_corridor_polygon_img": polygon,
    }


def compute_dynamic_corridor(
    lane_area: np.ndarray | None,
    frame_h: int,
    frame_w: int,
    *,
    top_frac: float = DEFAULT_TOP_FRAC,
    bottom_frac: float = DEFAULT_BOTTOM_FRAC,
    half_width_near_frac: float = DEFAULT_HALF_WIDTH_NEAR_FRAC,
    half_width_far_frac: float = DEFAULT_HALF_WIDTH_FAR_FRAC,
    num_points: int = DEFAULT_NUM_POINTS,
    min_row_pixels: int = DEFAULT_MIN_ROW_PIXELS,
    residual_trim_frac: float = DEFAULT_RESIDUAL_TRIM_FRAC,
) -> dict | None:
    """Single-frame dynamic corridor from a binary lane_area mask. Returns
    ``None`` when the mask is missing or has too few valid rows; otherwise a
    dict with the legacy ``fixed_*`` keys plus fit diagnostics."""
    if lane_area is None or lane_area.size == 0:
        return None
    if lane_area.shape[0] != frame_h or lane_area.shape[1] != frame_w:
        frame_h, frame_w = int(lane_area.shape[0]), int(lane_area.shape[1])
    top_cut = int(round(frame_h * top_frac))
    rows, cx, counts = _row_centroids(lane_area, top_cut, min_row_pixels)
    fit = _fit_quadratic(
        rows, cx, counts,
        residual_trim_frac=residual_trim_frac,
        frame_h=frame_h, frame_w=frame_w,
    )
    if fit is None:
        return None
    half_near = max(8.0, half_width_near_frac * float(frame_w))
    half_far = max(6.0, half_width_far_frac * float(frame_w))
    out = build_corridor_dict(
        fit.coeffs,
        frame_h=frame_h, frame_w=frame_w,
        top_frac=top_frac, bottom_frac=bottom_frac,
        half_width_near_px=half_near, half_width_far_px=half_far,
        num_points=num_points,
    )
    out.update(
        coeffs=fit.coeffs,
        confidence=fit.confidence,
        n_points=fit.n_points,
        rms_residual_px=fit.rms_residual_px,
        half_width_near_px=half_near,
        half_width_far_px=half_far,
        is_dynamic=True,
    )
    return out
